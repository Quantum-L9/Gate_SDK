#!/usr/bin/env python3
"""Fail closed unless every CI install is hash-locked and the locks agree.

Issue #53 (SonarCloud githubactions:S8541 / S8544): every workflow installed
from the index with no versions or hashes (`pip install -e ".[dev]"`,
`pip install pip-audit`, ...). The workflows now install only from the
hash-locked files under ``requirements/``, generated by
``scripts/lock_requirements.py``. This validator keeps that true:

1. every lock exists and every line is an exact ``==`` pin carrying sha256
   hashes (what ``pip install --require-hashes`` will demand anyway);
2. locks installed into the same environment agree: a lock compiled against a
   base pins every shared package exactly as the base does, and ``dev`` carries
   every ``runtime`` package — so CI tests the dependency set that ships;
3. every direct requirement (``pyproject.toml`` and ``requirements/*.in``) is
   satisfied by its lock, so a dependency added without regenerating fails here
   instead of resolving unhashed in CI;
4. no workflow ``pip install`` line is unlocked: each one is either a
   ``--require-hashes --only-binary :all: -r requirements/<x>.lock`` install or
   an offline ``--no-index --no-deps`` install of local code.

Offline and deterministic; hash *freshness* is pip's job at install time.
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

from packaging.requirements import InvalidRequirement, Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
LOCK_DIR = "requirements"
WORKFLOW_DIR = ".github/workflows"


@dataclass(frozen=True)
class LockSpec:
    """One hash-locked environment and how it is compiled."""

    name: str
    inputs: tuple[str, ...]
    extras: tuple[str, ...] = ()
    # Locks installed into the same environment before this one. Shared
    # packages are compiled as constraints, so their versions are identical.
    constrained_by: tuple[str, ...] = ()
    # Locks whose every package this one must also carry.
    superset_of: tuple[str, ...] = ()

    @property
    def path(self) -> str:
        return f"{LOCK_DIR}/{self.name}.lock"


# Generation order: a lock's bases come before it.
LOCKS: tuple[LockSpec, ...] = (
    LockSpec("runtime", ("pyproject.toml",)),
    LockSpec("build", (f"{LOCK_DIR}/build.in",)),
    LockSpec(
        "dev",
        ("pyproject.toml",),
        extras=("dev",),
        constrained_by=("runtime", "build"),
        superset_of=("runtime",),
    ),
    LockSpec("audit", (f"{LOCK_DIR}/audit.in",), constrained_by=("dev",)),
    LockSpec("precommit", (f"{LOCK_DIR}/precommit.in",), constrained_by=("dev",)),
    LockSpec("twine", (f"{LOCK_DIR}/twine.in",), constrained_by=("build",)),
    LockSpec("sbom", (f"{LOCK_DIR}/sbom.in",), constrained_by=("runtime",)),
)
SPECS = {spec.name: spec for spec in LOCKS}

HASH = r"--hash=sha256:[0-9a-f]{64}"
LOCK_LINE_RE = re.compile(
    rf"^(?P<name>[A-Za-z0-9][A-Za-z0-9._-]*)==(?P<version>[^\s;]+)(?:\s+{HASH})+$"
)
LOCKED_INSTALL_RE = re.compile(r"-r\s+requirements/[a-z]+\.lock\b")


def lock_pins(rel: str, text: str) -> tuple[dict[str, str], list[str]]:
    """Canonical name -> version for one lock, plus any malformed-line errors."""
    pins: dict[str, str] = {}
    errors: list[str] = []
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = LOCK_LINE_RE.match(line)
        if match is None:
            errors.append(f"{rel}:{number}: not an exact '==' pin with sha256 hashes: {line[:80]}")
            continue
        pins[canonicalize_name(match["name"])] = match["version"]
    if not pins and not errors:
        errors.append(f"{rel}: lock is empty")
    return pins, errors


def check_agreement(spec: LockSpec, pins: dict[str, dict[str, str]]) -> list[str]:
    """Locks that share an environment must pin shared packages identically."""
    errors: list[str] = []
    own = pins[spec.name]
    for base in spec.constrained_by:
        for name, version in sorted(own.items()):
            other = pins[base].get(name)
            if other is not None and other != version:
                errors.append(
                    f"{spec.path}: {name}=={version} but {SPECS[base].path} pins "
                    f"{name}=={other} — they install into one environment; "
                    "regenerate with scripts/lock_requirements.py"
                )
    for base in spec.superset_of:
        for name, version in sorted(pins[base].items()):
            if name not in own:
                errors.append(f"{spec.path}: missing {name}=={version} from {SPECS[base].path}")
    return errors


def direct_requirements(root: Path, spec: LockSpec) -> list[str]:
    """The requirement strings a lock is compiled from."""
    found: list[str] = []
    for rel in spec.inputs:
        path = root / rel
        if rel.endswith("pyproject.toml"):
            project = tomllib.loads(path.read_text(encoding="utf-8"))["project"]
            if spec.extras:
                optional = project.get("optional-dependencies", {})
                for extra in spec.extras:
                    found.extend(optional.get(extra, []))
            found.extend(project.get("dependencies", []))
        else:
            for raw in path.read_text(encoding="utf-8").splitlines():
                line = raw.split("#", 1)[0].strip()
                if line:
                    found.append(line)
    return found


def check_direct(root: Path, spec: LockSpec, own: dict[str, str]) -> list[str]:
    """A declared requirement the lock does not satisfy means the lock is stale."""
    errors: list[str] = []
    for text in direct_requirements(root, spec):
        try:
            requirement = Requirement(text)
        except InvalidRequirement as exc:
            errors.append(f"{spec.path}: cannot parse input requirement {text!r}: {exc}")
            continue
        if requirement.marker is not None and not requirement.marker.evaluate():
            continue
        name = canonicalize_name(requirement.name)
        version = own.get(name)
        if version is None:
            errors.append(
                f"{spec.path}: {requirement} is declared but not locked — "
                "regenerate with scripts/lock_requirements.py"
            )
        elif not requirement.specifier.contains(version, prereleases=True):
            errors.append(
                f"{spec.path}: locks {name}=={version}, which does not satisfy "
                f"declared {requirement} — regenerate"
            )
    return errors


def check_workflow_line(rel: str, number: int, raw: str) -> list[str]:
    """One workflow line: an install must be hash-locked or offline."""
    line = raw.strip()
    if line.startswith("#") or "pip install" not in line:
        return []
    if "--no-index" in line and "--no-deps" in line:
        return []
    missing = [flag for flag in ("--require-hashes", "--only-binary :all:") if flag not in line]
    if LOCKED_INSTALL_RE.search(line) is None:
        missing.append("-r requirements/<name>.lock")
    if not missing:
        return []
    return [f"{rel}:{number}: unlocked pip install (missing {', '.join(missing)}): {line[:100]}"]


def check_workflows(root: Path) -> list[str]:
    errors: list[str] = []
    workflow_dir = root / WORKFLOW_DIR
    for path in sorted(workflow_dir.glob("*.y*ml")):
        rel = path.relative_to(root).as_posix()
        for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
            errors.extend(check_workflow_line(rel, number, raw))
            for match in LOCKED_INSTALL_RE.finditer(raw):
                target = match.group(0).split()[-1]
                if not (root / target).is_file():
                    errors.append(f"{rel}:{number}: installs missing lock {target}")
    return errors


def check_tree(root: Path) -> list[str]:
    errors: list[str] = []
    pins: dict[str, dict[str, str]] = {}
    for spec in LOCKS:
        path = root / spec.path
        if not path.is_file():
            errors.append(f"{spec.path}: lock is missing — run scripts/lock_requirements.py")
            continue
        pins[spec.name], format_errors = lock_pins(spec.path, path.read_text(encoding="utf-8"))
        errors.extend(format_errors)
    for spec in LOCKS:
        if spec.name not in pins:
            continue
        if all(base in pins for base in (*spec.constrained_by, *spec.superset_of)):
            errors.extend(check_agreement(spec, pins))
        errors.extend(check_direct(root, spec, pins[spec.name]))
    errors.extend(check_workflows(root))
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    errors = check_tree(args.root)
    if errors:
        print("FAIL")
        print("\n".join(errors))
        return 1
    print(f"PASS {len(LOCKS)} hash-locked environments agree; every workflow install is locked")
    return 0


if __name__ == "__main__":
    sys.exit(main())
