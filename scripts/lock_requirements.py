#!/usr/bin/env python3
"""Regenerate the hash-locked CI environments under ``requirements/``.

Every lock is ``uv pip compile --generate-hashes`` output for Python 3.12,
compacted to one requirement per line with every sha256 kept, so each file
installs with ``pip install --require-hashes``. The set of locks, their inputs
and which lock is compiled against which, live in one registry:
``scripts/validate_locks.py`` (``LOCKS``) — the same registry the validator
checks, so the generator and the gate cannot disagree about what exists.

A lock with bases is compiled with the bases' pins as constraints: locks that
install into one environment then pin every shared package identically.

A refresh is scoped. Each committed lock seeds uv's output file, which uv
treats as version preferences, so regenerating after an input change does not
silently move unrelated packages. Set ``LOCK_UPGRADE_ALL=1`` for a deliberate,
reviewable full dependency refresh.

Usage: python scripts/lock_requirements.py   (needs uv on PATH)
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

# Run as `python scripts/lock_requirements.py`, so scripts/ is sys.path[0].
from validate_locks import LOCKS, ROOT, SPECS, LockSpec, check_tree, lock_pins

PYTHON_VERSION = "3.12"


def compact(text: str) -> str:
    """Join continuation lines; one requirement per line, every hash kept."""
    lines: list[str] = []
    current = ""
    for raw in text.splitlines():
        stripped = raw.strip()
        if not stripped or stripped.startswith("#"):
            continue
        if stripped.endswith("\\"):
            current += stripped[:-1].strip() + " "
            continue
        lines.append((current + stripped).strip())
        current = ""
    return "".join(f"{line}\n" for line in sorted(lines, key=str.lower))


def header(spec: LockSpec) -> str:
    inputs = " ".join(spec.inputs)
    if spec.extras:
        inputs += f" [{','.join(spec.extras)}]"
    against = ""
    if spec.constrained_by:
        against = " Compiled against: " + ", ".join(f"{b}.lock" for b in spec.constrained_by) + "."
    return (
        "# Generated by scripts/lock_requirements.py -- do not edit by hand.\n"
        f"# Inputs: {inputs}.{against}\n"
        f"# Install with: pip install --require-hashes --only-binary :all: -r {spec.path}\n"
    )


def base_constraints(spec: LockSpec) -> str:
    pins: dict[str, str] = {}
    for base in spec.constrained_by:
        rel = SPECS[base].path
        found, errors = lock_pins(rel, (ROOT / rel).read_text(encoding="utf-8"))
        if errors:
            raise SystemExit("\n".join(errors))
        pins.update(found)
    return "".join(f"{name}=={version}\n" for name, version in sorted(pins.items()))


def compile_lock(spec: LockSpec, upgrade_all: bool) -> None:
    out = ROOT / spec.path
    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        result = tmp_dir / "out.txt"
        if out.is_file() and not upgrade_all:
            shutil.copyfile(out, result)  # version preferences for a scoped refresh
        cmd = ["uv", "pip", "compile", *spec.inputs]
        cmd += ["--python-version", PYTHON_VERSION, "--generate-hashes"]
        cmd += ["--no-header", "--no-annotate", "--quiet", "-o", str(result)]
        for extra in spec.extras:
            cmd += ["--extra", extra]
        if upgrade_all:
            cmd.append("--upgrade")
        if spec.constrained_by:
            constraints = tmp_dir / "constraints.txt"
            constraints.write_text(base_constraints(spec), encoding="utf-8")
            cmd += ["--constraint", str(constraints)]
        subprocess.run(cmd, cwd=ROOT, check=True)
        body = compact(result.read_text(encoding="utf-8"))
    out.write_text(header(spec) + body, encoding="utf-8")
    print(f"wrote {spec.path} ({body.count(chr(10))} packages)")


def main() -> int:
    if shutil.which("uv") is None:
        print("FAIL: uv is required (https://docs.astral.sh/uv/)", file=sys.stderr)
        return 1
    upgrade_all = os.environ.get("LOCK_UPGRADE_ALL") == "1"
    for spec in LOCKS:
        compile_lock(spec, upgrade_all)
    errors = check_tree(ROOT)
    if errors:
        print("FAIL\n" + "\n".join(errors), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
